import { comparableArabic } from "./category-registry";

// ── إنشاء الـ Sets للبحث السريع O(1) ──
export const EGYPTIAN_MALE_NAMES = new Set(
  MALE_NAMES_LIST.map((n) => comparableArabic(n.trim())),
);
export const EGYPTIAN_FEMALE_NAMES = new Set(
  FEMALE_NAMES_LIST.map((n) => comparableArabic(n.trim())),
);
export const FAMILY_TERMS = new Set(
  FAMILY_TERMS_LIST.map((n) => comparableArabic(n.trim())),
);
export const MERCHANT_NEGATIVE_LIST = new Set(
  MERCHANT_NEGATIVE_LIST_ITEMS.map((n) => comparableArabic(n.trim())),
);
export const ALL_KNOWN_NAMES = new Set([
  ...EGYPTIAN_MALE_NAMES,
  ...EGYPTIAN_FEMALE_NAMES,
]);

/**
 * يتحقق إذا كانت الكلمة على الأرجح اسم شخص
 * @returns true لو الكلمة اسم شخص معروف أو مصطلح عائلي
 */
export function isLikelyPersonName(word: string): boolean {
  if (!word || word.length < 2) return false;
  if (/^\d+$/.test(word)) return false;
  const clean = comparableArabic(word.trim());
  if (MERCHANT_NEGATIVE_LIST.has(clean)) return false;
  return ALL_KNOWN_NAMES.has(clean) || FAMILY_TERMS.has(clean);
}

/**
 * يتحقق إذا كانت الكلمة مصطلح عائلي (ماما، بابا، أخويا، إلخ)
 */
export function isFamilyTerm(word: string): boolean {
  return FAMILY_TERMS.has(comparableArabic(word.trim()));
}

/**
 * يتحقق إذا كانت الكلمة اسم متجر/مكان (Negative List)
 */
export function isMerchantOrPlace(word: string): boolean {
  return MERCHANT_NEGATIVE_LIST.has(comparableArabic(word.trim()));
}
