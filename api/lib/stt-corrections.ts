/**
 * Apply STT corrections to text.
 * Replaces known misspelled words with their correct forms.
 */
export function applySttCorrections(text: string): string {
  let result = text;

  // Sort keys by length (longest first) to avoid partial replacements
  const sortedKeys = Object.keys(STT_CORRECTION_MAP).sort(
    (a, b) => b.length - a.length,
  );

  for (const wrong of sortedKeys) {
    // Word boundary-aware replacement using split/join for simple cases
    // and regex for more complex patterns
    const escaped = wrong.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const regex = new RegExp(`(?:^|(?<=\\s))${escaped}(?=\\s|$)`, "g");
    result = result.replace(regex, STT_CORRECTION_MAP[wrong]);
  }

  return result;
}

/**
 * Damerau-Levenshtein distance (C-optimized, replaces hand-rolled version).
 * Used for fuzzy correction of unknown words against dictionary keys.
 */
export function levenshteinDistance(a: string, b: string): number {
  return damerauLevenshtein(a, b);
}

/**
 * Fuzzy-correct a word against known financial vocabulary.
 * Returns the corrected word if a close match (distance ≤ maxDist) is found,
 * otherwise returns the original word.
 */
export function fuzzyCorrectWord(
  word: string,
  knownWords: string[],
  maxDist: number = 2,
): string {
  if (word.length < 3) return word; // Too short to fuzzy match

  let bestMatch = word;
  let bestDist = maxDist + 1;

  for (const known of knownWords) {
    // Skip if length difference is too large
    if (Math.abs(word.length - known.length) > maxDist) continue;

    const dist = levenshteinDistance(word, known);
    if (dist < bestDist) {
      bestDist = dist;
      bestMatch = known;
    }
    if (dist === 0) break; // Exact match
  }

  return bestDist <= maxDist ? bestMatch : word;
}
