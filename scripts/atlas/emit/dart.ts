/**
 * The procedure catalog of the Flutter app (docs/decisions/0022-flutter-mobile-app.md): one Dart constant per tRPC
 * procedure, so the mobile client can only call procedures that exist, with the HTTP method their kind needs.
 */
import type { AtlasGraph } from "../graph";
import type { ProcedureInfo } from "../extract/api";
import { compareStrings } from "../lib/util";

export const MOBILE_API_GENERATED_DIR = "mobile/packages/smartspend_api/lib/src/generated";

/** Builders that only staff may call. The mobile app is for users, so their procedures stay out of its catalog. */
const STAFF_BUILDERS = new Set(["adminProcedure", "moderatorProcedure"]);

const KIND_CLASS: Record<string, string> = {
  query: "ApiQuery",
  mutation: "ApiMutation",
  subscription: "ApiSubscription",
};

/** Words Dart refuses as a member name. */
const DART_RESERVED = new Set([
  "assert", "break", "case", "catch", "class", "const", "continue", "default", "do", "else", "enum", "extends",
  "false", "final", "finally", "for", "if", "in", "is", "new", "null", "rethrow", "return", "super", "switch", "this",
  "throw", "true", "try", "var", "void", "while", "with",
]);

function memberName(name: string): string {
  return DART_RESERVED.has(name) ? `${name}$` : name;
}

function className(routerKey: string): string {
  const words = routerKey.split(/[^a-zA-Z0-9]+/).filter(Boolean);
  return `${words.map((word) => word[0].toUpperCase() + word.slice(1)).join("")}Procedures`;
}

function constant(procedure: ProcedureInfo): string {
  const type = KIND_CLASS[procedure.kind];
  const args = [`'${procedure.path}'`, `builder: '${procedure.builder}'`];
  if (procedure.hasInput) args.push("hasInput: true");
  return `  ${type} get ${memberName(procedure.name)} => const ${type}(${args.join(", ")});`;
}

export function renderDart(graph: AtlasGraph): Map<string, string> {
  const routers = graph.api.routers
    .map((router) => ({
      ...router,
      procedures: router.procedures
        .filter((procedure) => !STAFF_BUILDERS.has(procedure.builder) && KIND_CLASS[procedure.kind])
        .sort((a, b) => compareStrings(a.name, b.name)),
    }))
    .filter((router) => router.procedures.length > 0)
    .sort((a, b) => compareStrings(a.key, b.key));

  const out: string[] = [
    "// GENERATED by `npm run atlas` from the source code. Do not edit: the next run overwrites this file.",
    "// Every tRPC procedure in api/router.ts that a visitor or a signed-in user may call; staff procedures are left",
    "// out. A procedure renamed or removed on the server disappears here, and Dart code still calling it stops",
    "// compiling.",
    "",
    "// `npm run atlas` compares this file byte for byte, so the Dart formatter leaves it as written.",
    "// dart format off",
    "",
    "import '../procedure.dart';",
    "",
    "/// The procedures, grouped by router: `Procedures.expense.list`.",
    "abstract final class Procedures {",
    ...routers.map((router) => `  static const ${memberName(router.key)} = ${className(router.key)}._();`),
    "}",
  ];

  for (const router of routers) {
    out.push(
      "",
      `/// The \`${router.key}\` router, \`${router.file}\`.`,
      `final class ${className(router.key)} {`,
      `  const ${className(router.key)}._();`,
      "",
      ...router.procedures.map(constant),
      "}",
    );
  }

  return new Map([[`${MOBILE_API_GENERATED_DIR}/procedures.g.dart`, `${out.join("\n")}\n`]]);
}
