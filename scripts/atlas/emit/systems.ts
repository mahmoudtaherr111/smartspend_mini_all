/**
 * One facts page per system in docs/architecture/systems.json, plus an index, written to docs/atlas/systems/.
 *
 * A page draws what the system is made of (screens, API, routes and jobs, code modules, tables, outside
 * systems and the other systems it depends on) and the journeys drawn for it in docs/architecture/flows,
 * then lists the same facts in tables. Mermaid diagrams render on GitHub, so anyone can read them without
 * tools. The explanation in prose sits beside these pages: docs/systems/<id>.md for engineers and agents,
 * docs/ar/systems/<id>.md for everyone else.
 */
