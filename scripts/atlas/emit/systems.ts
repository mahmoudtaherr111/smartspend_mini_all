/** Which system's explanation describes each source file: the reverse of every system's coverage. */
function renderFileIndex(graph: AtlasGraph): string {
  const rows = new Map<string, Map<string, string[]>>();
  for (const system of graph.systems.systems) {
    for (const unit of system.coverage) {
      const parts = rows.get(unit.file) ?? new Map<string, string[]>();
      parts.set(system.id, [...(parts.get(system.id) ?? []), unit.id === unit.file ? "" : unit.id.slice(unit.file.length + 1)]);
      rows.set(unit.file, parts);
    }
  }
  const link = (id: string) => `[${id}](${id}.md)`;
  const cell = (parts: Map<string, string[]>) => {
    const ids = [...parts.keys()].sort(compareStrings);
    const whole = ids.filter((id) => parts.get(id)!.includes(""));
    const declared = ids
      .map((id) => [id, parts.get(id)!.filter((part) => part && part !== REST_OF_FILE).sort(compareStrings)] as const)
      .filter(([, list]) => list.length > 0);
    const rest = ids.filter((id) => parts.get(id)!.includes(REST_OF_FILE));
    return [
      ...whole.map(link),
      ...declared.map(([id, list]) => `${link(id)}: ${list.map(code).join(", ")}`),
      ...(rest.length > 0 ? [`rest of the file: ${rest.map(link).join(", ")}`] : []),
    ].join(" · ");
  };

  return `${[
    BANNER,
    "# Systems by file",
    [
      "Which system's explanation describes each source file. Before you change a file, read `docs/systems/<id>.md` of its systems; after the change, `npm run agent:finish` asks for a new check of every explanation whose code changed.",
      "Most files belong to one system. A file whose procedures, routes or jobs belong to several systems is split: each declaration belongs to the system that owns it, and the rest of the file to all of them (to the server platform, for `api/boot.ts` and `api/server.ts`).",
    ].join("\n\n"),
    mdTable(
      ["File", "Systems"],
      [...rows.keys()].sort(compareStrings).map((file) => [code(file), cell(rows.get(file)!)]),
    ),
  ].join("\n\n")}\n`;
}

export function renderSystems(graph: AtlasGraph): Map<string, string> {
  const flows = readFlows();
  const labelOf = participantLabeler(graph);
  const dependencies = systemDependencies(graph);
  return new Map([
    [`${SYSTEMS_DIR}/README.md`, renderIndex(graph, dependencies)],
    [`${SYSTEMS_DIR}/files.md`, renderFileIndex(graph)],
    ...renderState(graph, SYSTEMS_DIR),
    ...graph.systems.systems.map(
      (system): [string, string] => [`${SYSTEMS_DIR}/${system.id}.md`, renderSystem(graph, system, flows, labelOf, dependencies)],
    ),
  ]);
}
