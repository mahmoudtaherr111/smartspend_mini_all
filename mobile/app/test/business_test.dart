import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:smartspend_app/src/features/business/business_models.dart';
import 'package:smartspend_app/src/features/business/business_providers.dart';
import 'package:smartspend_app/src/features/business/business_screen.dart';
import 'package:smartspend_app/src/features/plans/plan_models.dart';
import 'package:smartspend_app/src/features/plans/plan_providers.dart';
import 'package:smartspend_app/src/routing/app_router.dart';

import 'support/test_app.dart';

void main() {
  group('Business Models (BIZ-01..04)', () {
    test('BusinessInfo json parsing', () {
      final info = BusinessInfo.fromJson({
        'id': 10,
        'name': 'متجر النور',
        'type': 'retail',
        'typeLabel': 'محل تجاري / تجزئة',
        'description': 'محل أدوات منزلية',
        'keywords': <String>['فاتورة', 'مورد'],
        'isActive': true,
      });

      expect(info.id, 10);
      expect(info.name, 'متجر النور');
      expect(info.type, 'retail');
      expect(info.typeLabel, 'محل تجاري / تجزئة');
      expect(info.description, 'محل أدوات منزلية');
      expect(info.keywords, contains('فاتورة'));
      expect(info.isActive, isTrue);
    });

    test('BusinessCategory json roundtrip', () {
      final cat = BusinessCategory.fromJson({
        'id': 5,
        'name': 'raw_materials',
        'nameAr': 'مواد خام',
        'icon': '📦',
        'color': '#10b981',
        'type': 'expense',
        'keywords': <String>['خشب', 'قماش'],
        'matchExamples': <String>['شراء قماش'],
        'isAutoGenerated': true,
      });

      expect(cat.id, 5);
      expect(cat.nameAr, 'مواد خام');
      expect(cat.icon, '📦');
      expect(cat.type, 'expense');

      final json = cat.toJson();
      expect(json['name'], 'raw_materials');
      expect(json['nameAr'], 'مواد خام');
    });

    test('BusinessState model', () {
      final state = BusinessState.fromJson({
        'business': {
          'id': 1,
          'name': 'ورشة النجارة',
          'type': 'services',
          'typeLabel': 'خدمات',
          'isActive': true,
        },
        'categories': [
          {
            'id': 1,
            'name': 'supplies',
            'nameAr': 'مستلزمات',
            'icon': '🔧',
            'type': 'expense',
          }
        ],
        'contactCount': 3,
      });

      expect(state.hasBusiness, isTrue);
      expect(state.business?.name, 'ورشة النجارة');
      expect(state.categories.length, 1);
      expect(state.contactCount, 3);
    });
  });

  group('Business Providers & Screen (BIZ-01..04)', () {
    test('isBusinessModeActiveProvider toggles properly', () {
      final container = ProviderContainer();
      addTearDown(container.dispose);

      expect(container.read(isBusinessModeActiveProvider), isFalse);
      container.read(isBusinessModeActiveProvider.notifier).set(true);
      expect(container.read(isBusinessModeActiveProvider), isTrue);
      container.read(isBusinessModeActiveProvider.notifier).toggle();
      expect(container.read(isBusinessModeActiveProvider), isFalse);
    });

    testWidgets('displays creation form when no business exists', (tester) async {
      final api = FakeApi();
      api.answer('localAuth.me', (_) => phoneUser());
      api.answer('business.get', (_) => {'business': null, 'categories': <Map<String, Object?>>[], 'contactCount': 0});
      api.answer('business.types', (_) => [
        {'id': 'retail', 'label': 'محل تجاري', 'icon': '🛍️'},
      ]);
      api.answer('pro.myPlan', (_) => {
        'plan': 'pro',
        'role': 'user',
        'features': {'business': true},
      });

      final app = TestApp(
        token: 'token',
        api: api,
        overrides: [
          userPlanProvider.overrideWith(
            (ref) async => const UserPlanInfo(plan: 'pro', role: 'user', businessEnabled: true),
          ),
        ],
      );
      await app.pump(tester);

      app.container.read(routerProvider).go(BusinessScreen.path);
      await tester.pumpAndSettle();

      expect(find.text('إعداد حساب الشغل'), findsOneWidget);
      expect(find.text('اسم المشروع أو المتجر'), findsOneWidget);
    });

    testWidgets('displays active business when already created', (tester) async {
      final api = FakeApi();
      api.answer('localAuth.me', (_) => phoneUser());
      api.answer('business.get', (_) => {
        'business': {
          'id': 1,
          'name': 'مكتبتي',
          'type': 'retail',
          'typeLabel': 'مكتبة وتجزئة',
          'isActive': true,
        },
        'categories': [
          {
            'id': 101,
            'name': 'books',
            'nameAr': 'كتب وأدوات',
            'icon': '📚',
            'type': 'expense',
          }
        ],
        'contactCount': 2,
      });
      api.answer('pro.myPlan', (_) => {
        'plan': 'pro',
        'role': 'user',
        'features': {'business': true},
      });

      final app = TestApp(
        token: 'token',
        api: api,
        overrides: [
          userPlanProvider.overrideWith(
            (ref) async => const UserPlanInfo(plan: 'pro', role: 'user', businessEnabled: true),
          ),
        ],
      );
      await app.pump(tester);

      app.container.read(routerProvider).go(BusinessScreen.path);
      await tester.pumpAndSettle();

      expect(find.text('مكتبتي'), findsOneWidget);
      expect(find.text('مكتبة وتجزئة'), findsOneWidget);
      expect(find.text('كتب وأدوات'), findsOneWidget);
      expect(find.byType(Switch), findsOneWidget);
    });
  });
}
