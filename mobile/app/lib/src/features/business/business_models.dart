/// Models for Business mode (BIZ-01..BIZ-04).
library;

/// A user's business entity (BIZ-01).
final class BusinessInfo {
  const BusinessInfo({
    required this.id,
    required this.name,
    required this.type,
    required this.typeLabel,
    this.description = '',
    this.keywords = const [],
    this.isActive = true,
  });

  factory BusinessInfo.fromJson(Map<String, Object?> json) {
    final rawKeywords = json['keywords'] as List<Object?>? ?? const [];
    return BusinessInfo(
      id: (json['id'] as num?)?.toInt() ?? 0,
      name: (json['name'] as String?) ?? '',
      type: (json['type'] as String?) ?? 'custom',
      typeLabel: (json['typeLabel'] as String?) ?? (json['type'] as String? ?? ''),
      description: (json['description'] as String?) ?? '',
      keywords: [for (final k in rawKeywords) if (k is String) k],
      isActive: json['isActive'] != false,
    );
  }

  final int id;
  final String name;
  final String type;
  final String typeLabel;
  final String description;
  final List<String> keywords;
  final bool isActive;
}

/// A category specific to a business (BIZ-02).
final class BusinessCategory {
  const BusinessCategory({
    required this.id,
    required this.name,
    required this.nameAr,
    this.icon = '🛍️',
    this.color = '#3b82f6',
    this.type = 'expense',
    this.keywords = const [],
    this.matchExamples = const [],
    this.isAutoGenerated = true,
  });

  factory BusinessCategory.fromJson(Map<String, Object?> json) {
    final rawKeywords = json['keywords'] as List<Object?>? ?? const [];
    final rawExamples = json['matchExamples'] as List<Object?>? ?? const [];
    return BusinessCategory(
      id: (json['id'] as num?)?.toInt() ?? 0,
      name: (json['name'] as String?) ?? '',
      nameAr: (json['nameAr'] as String?) ?? (json['name'] as String? ?? ''),
      icon: (json['icon'] as String?) ?? '🛍️',
      color: (json['color'] as String?) ?? '#3b82f6',
      type: (json['type'] as String?) ?? 'expense',
      keywords: [for (final k in rawKeywords) if (k is String) k],
      matchExamples: [for (final e in rawExamples) if (e is String) e],
      isAutoGenerated: json['isAutoGenerated'] != false,
    );
  }

  final int id;
  final String name;
  final String nameAr;
  final String icon;
  final String color;
  final String type;
  final List<String> keywords;
  final List<String> matchExamples;
  final bool isAutoGenerated;

  Map<String, Object?> toJson() => {
    'name': name,
    'nameAr': nameAr,
    'icon': icon,
    'color': color,
    'type': type,
    'keywords': keywords,
    'matchExamples': matchExamples,
    'isAutoGenerated': isAutoGenerated,
  };
}

/// Preset business types (BIZ-01).
final class BusinessTypeOption {
  const BusinessTypeOption({
    required this.id,
    required this.label,
    required this.icon,
  });

  factory BusinessTypeOption.fromJson(Map<String, Object?> json) {
    return BusinessTypeOption(
      id: (json['id'] as String?) ?? 'custom',
      label: (json['label'] as String?) ?? '',
      icon: (json['icon'] as String?) ?? '💼',
    );
  }

  final String id;
  final String label;
  final String icon;
}

/// Aggregated dashboard state for business mode (BIZ-01..04).
final class BusinessState {
  const BusinessState({
    this.business,
    this.categories = const [],
    this.contactCount = 0,
  });

  factory BusinessState.fromJson(Map<String, Object?> json) {
    final b = json['business'];
    final rawCats = json['categories'] as List<Object?>? ?? const [];
    return BusinessState(
      business: b is Map<String, Object?> ? BusinessInfo.fromJson(b) : null,
      categories: [
        for (final c in rawCats)
          if (c is Map<String, Object?>) BusinessCategory.fromJson(c),
      ],
      contactCount: (json['contactCount'] as num?)?.toInt() ?? 0,
    );
  }

  final BusinessInfo? business;
  final List<BusinessCategory> categories;
  final int contactCount;

  bool get hasBusiness => business != null && business!.isActive;
}
